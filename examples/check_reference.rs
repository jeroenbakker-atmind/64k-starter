fn main() {
    let parsed = decode(REFERENCE_BLOB).expect("reference blob should decode cleanly");

    println!("tempo       = {}", parsed.tempo);
    println!("sample_rate = {}", parsed.sample_rate);
    println!("length      = {:.6}s", parsed.length);
    println!("devices     = {} ({:?})", parsed.devices.len(), parsed.devices[0].id);
    println!("midi lanes  = {}", parsed.lanes.len());
    for (i, lane) in parsed.lanes.iter().enumerate() {
        let ons = lane.iter().filter(|e| e.on).count();
        let offs = lane.iter().filter(|e| !e.on).count();
        println!("  lane {i}: {} events ({ons} on, {offs} off)", lane.len());
    }
    println!("tracks      = {}", parsed.tracks.len());
    for (i, t) in parsed.tracks.iter().enumerate() {
        println!(
            "  track {i}: volume={:.3} receives={} devices={} lane={}",
            t.volume,
            t.receives.len(),
            t.device_indices.len(),
            t.lane_id
        );
    }

    let mut ok = true;
    ok &= parsed.tempo == 140;
    ok &= parsed.sample_rate == 44100;
    ok &= parsed.devices.len() == 1 && parsed.devices[0].id == DeviceId::Slaughter;
    ok &= parsed.lanes.len() == 2;
    ok &= parsed.lanes[0].len() == 32;
    ok &= parsed.lanes[1].is_empty();
    ok &= parsed.tracks.len() == 3;
    ok &= parsed.tracks[0].device_indices.len() == 1;
    ok &= parsed.tracks[1].receives.len() == 1;
    ok &= parsed.tracks[2].receives.len() == 1;

    // Every event must be a sane note.
    for lane in &parsed.lanes {
        for e in lane {
            ok &= (e.velocity == 0) == !e.on;
            ok &= e.note < 128;
        }
    }

    assert!(ok, "reference blob does not match the expected structure");
    println!("OK: decode of a real WaveSabre song matches the C#/C++ format");
}